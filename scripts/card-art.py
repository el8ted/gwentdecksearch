"""Fetches filter icons into src/icons and lists their card IDs in src/art.ts.

- Stratagems: card art cropped to a square, src/icons/s-{id}.webp.
- Leaders: the game's ability icon, src/icons/l-{id}.webp.

Reads data/cache/card-search/{all,leaders}.json (run `pnpm scrape:cards` first) and needs Pillow.
Run again when CDPR adds a leader or stratagem.

    python3 scripts/card-art.py && pnpm check:fix
"""

import io
import json
import time
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SIZE = 80  # 2x the 40px tile, sharp on high-DPI screens
CROP = 0.8  # of the card width: a stratagem's item sits centred, a little above middle


def fetch(path: str) -> Image.Image:
    req = urllib.request.Request("https://www.playgwent.com" + path, headers={"User-Agent": "gwent-deck-search (icons)"})
    time.sleep(0.5)
    return Image.open(io.BytesIO(urllib.request.urlopen(req).read()))


def cards(file: str):
    return (c["_source"] for c in json.loads((ROOT / f"data/cache/card-search/{file}").read_text()))


ids = []
for card in cards("all.json"):
    if card["type"] != 16:  # stratagem
        continue
    im = fetch(card["preview_img_path"]["big"]).convert("RGB")
    w, h = im.size
    s = int(w * CROP)
    x, y = (w - s) // 2, int(h * 0.48 - s / 2)
    im.crop((x, y, x + s, y + s)).resize((SIZE, SIZE), Image.LANCZOS).save(ROOT / f"src/icons/s-{card['id']}.webp", quality=82)
    ids.append(card["id"])
for card in cards("leaders.json"):
    im = fetch(card["ability_img_path"]["big"]).convert("RGBA")
    im.resize((SIZE, SIZE), Image.LANCZOS).save(ROOT / f"src/icons/l-{card['id']}.webp", quality=90)
    ids.append(card["id"])

body = ", ".join(str(i) for i in sorted(ids))
(ROOT / "src/art.ts").write_text(
    "// Generated by scripts/card-art.py: leaders and stratagems with an icon in src/icons.\n"
    f"export const CARD_ART: ReadonlySet<number> = new Set([{body}])\n"
)
print(f"{len(ids)} icons")
